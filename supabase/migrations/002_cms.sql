-- WordPress（cms.getabarrel.com / Hetzner）を廃止し、記事の保管庫を Supabase に移す。
-- id は WP の投稿IDをそのまま引き継ぐ（Sheet の wp_post_id・SNS在庫が参照しているため）。新規は 5000 から採番。
-- slug は WP と同じ「小文字のパーセントエンコード」で保存する（Google に登録済みのURLと一致させるため）。

create table if not exists public.categories (
  id          integer     primary key,
  name        text        not null,
  slug        text        not null unique,
  parent      integer     not null default 0,
  description text        not null default ''
);

create table if not exists public.posts (
  id                 bigint      generated by default as identity (start with 5000) primary key,
  slug               text        unique,
  status             text        not null default 'draft' check (status in ('draft', 'publish', 'trash')),
  title              text        not null,
  content            text        not null default '',
  excerpt            text        not null default '',
  category_ids       integer[]   not null default '{}',
  featured_image_url text,
  featured_image_alt text        not null default '',
  date               timestamptz not null default now(),
  modified           timestamptz not null default now(),
  created_at         timestamptz not null default now()
);

create index if not exists posts_status_date_idx on public.posts (status, date desc);
create index if not exists posts_category_ids_idx on public.posts using gin (category_ids);

-- WP の modified と同じく、更新のたびに更新日時を進める
create or replace function public.touch_modified() returns trigger language plpgsql as $$
begin
  new.modified := now();
  return new;
end $$;

drop trigger if exists posts_touch_modified on public.posts;
create trigger posts_touch_modified before update on public.posts
  for each row
  when (old.title is distinct from new.title or old.content is distinct from new.content or old.excerpt is distinct from new.excerpt)
  execute function public.touch_modified();

-- 表側（anon キー）は公開記事とカテゴリの読み取りだけ。書き込みはエンジンの service_role キーのみ（RLSを迂回する）
alter table public.categories enable row level security;
alter table public.posts      enable row level security;

drop policy if exists "categories are public" on public.categories;
create policy "categories are public" on public.categories for select using (true);

drop policy if exists "published posts are public" on public.posts;
create policy "published posts are public" on public.posts for select using (status = 'publish');

-- アップロードした画像の台帳（旧 WP メディアライブラリ）。エンジンは uploadMedia → setFeaturedImage を ID で受け渡すため残す。
-- ファイル名（Unsplashの写真ID）から、同じ写真の使い回しを避ける判定（usedPhotoIds）にも使う
create table if not exists public.media (
  id         bigint      generated by default as identity (start with 5000) primary key,
  path       text        not null unique,
  url        text        not null,
  caption    text        not null default '',
  alt_text   text        not null default '',
  created_at timestamptz not null default now()
);
alter table public.media enable row level security;

-- 画像置き場（旧 wp-content/uploads）
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do nothing;

