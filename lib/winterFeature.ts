/** 大会期間（日本時間の日付。両端を含む）。決勝は 2026-11-24 10:00 */
export const TOURNAMENT_START = "2026-11-19";
export const TOURNAMENT_END = "2026-11-24";

export type FeaturePhase = "before" | "tournament" | "winter";

/** 日本時間の日付 "YYYY-MM-DD"。サーバーのタイムゾーン（Vercel は UTC）に関係なく決まるよう、UTC に9時間足して切り出す */
export function jstDate(now: Date): string {
  return new Date(now.getTime() + 9 * 3_600_000).toISOString().slice(0, 10);
}

/** 大会前は出さない／大会期間は神宮大会版／翌日（11/25）以降は冬季版。冬季版に終わりは無い */
export function featurePhase(now: Date): FeaturePhase {
  const d = jstDate(now);
  if (d < TOURNAMENT_START) return "before";
  if (d <= TOURNAMENT_END) return "tournament";
  return "winter";
}

